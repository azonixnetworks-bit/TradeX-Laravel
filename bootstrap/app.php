<?php

use App\Console\Commands\AdminReleaseCheckCommand;
use App\Console\Commands\MobileApiReleaseCheckCommand;
use App\Console\Commands\NowPaymentsCheckCommand;
use App\Console\Commands\StripeCheckCommand;
use App\Http\Middleware\AdminAuthenticate;
use App\Http\Middleware\AdminSecurityHeaders;
use App\Http\Middleware\EnsureTradeXMobileApiSession;
use App\Http\Middleware\EnsureTradingFloorAccessDevice;
use App\Http\Middleware\ForceAdminTotp;
use App\Http\Middleware\HardenAdminSession;
use App\Http\Middleware\HardenMobileApiRequests;
use App\Support\Admin\AdminWebExceptionResponder;
use Illuminate\Foundation\Application;
use Illuminate\Foundation\Configuration\Exceptions;
use Illuminate\Foundation\Configuration\Middleware;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Route;

return Application::configure(basePath: dirname(__DIR__))
    ->withRouting(
        web: __DIR__.'/../routes/web.php',
        api: __DIR__.'/../routes/api.php',
        commands: __DIR__.'/../routes/console.php',
        health: '/up',
        then: function (): void {
            Route::middleware('api')
                ->prefix('api')
                ->group(base_path('routes/api_trading_floor_memberships.php'));
        },
    )
    ->withCommands([
        AdminReleaseCheckCommand::class,
        MobileApiReleaseCheckCommand::class,
        NowPaymentsCheckCommand::class,
        StripeCheckCommand::class,
    ])
    ->withMiddleware(function (Middleware $middleware): void {
        /*
         * Local HTTPS tunnels such as ngrok terminate TLS before forwarding
         * the request to Laravel over loopback HTTP. Trust loopback proxies
         * only, so Laravel can safely honor the forwarded HTTPS scheme/host
         * without trusting arbitrary internet-supplied proxy headers.
         */
        $middleware->trustProxies(
            at: [
                '127.0.0.1',
                '::1',
            ],
            headers:
                Request::HEADER_X_FORWARDED_FOR
                | Request::HEADER_X_FORWARDED_HOST
                | Request::HEADER_X_FORWARDED_PORT
                | Request::HEADER_X_FORWARDED_PROTO
        );

        /*
         * API-23 final hardening is installed once on Laravel's api group.
         * This covers routes/api.php plus provider-loaded API route files
         * without rewriting frozen API-01...22 route contracts.
         */
        $middleware->prependToGroup(
            'api',
            HardenMobileApiRequests::class
        );

        /*
         * ADMIN-19 web-group hardening is path-scoped internally to /admin.
         * Non-admin web requests pass through unchanged.
         *
         * Header middleware is prepended so its response headers also
         * cover redirects generated by the later session/TOTP middleware.
         */
        $middleware->prependToGroup(
            'web',
            AdminSecurityHeaders::class
        );

        $middleware->appendToGroup(
            'web',
            HardenAdminSession::class
        );

        $middleware->appendToGroup(
            'web',
            ForceAdminTotp::class
        );

        $middleware->appendToGroup('web', \App\Http\Middleware\EnsureAdminDevice::class);

        $middleware->alias([
            'admin.auth' => AdminAuthenticate::class,
            'tradex.mobile' => EnsureTradeXMobileApiSession::class,
            'trading.floor.device' => EnsureTradingFloorAccessDevice::class,
        ]);
    })
    ->withExceptions(function (Exceptions $exceptions): void {
        $exceptions->shouldRenderJsonWhen(
            fn (Request $request) => $request->is('api/*')
                || $request->expectsJson(),
        );

        /*
         * ADMIN-20D: HTML admin requests get a controlled error boundary.
         * API requests remain on their existing JSON exception contracts.
         */
        $exceptions->render(
            function (\Throwable $exception, Request $request) {
                return app(
                    AdminWebExceptionResponder::class
                )->render(
                    $exception,
                    $request
                );
            }
        );
    })
    ->create();
